#!/usr/bin/env bash
# Driver matrix checks that run without a VM.
#
# Each case points detect_os at an os-release fixture, puts a stub tool directory in
# front of PATH, and calls the loaded driver with DRY_RUN=1. The commands the driver
# prints are the result, so a distribution can be verified on any Linux runner and
# nothing is installed.
#
# The dnf-versus-yum choice depends on what the runner has installed, so RPM cases
# assert on package names and family behaviour rather than the binary name.
#
# Usage: bash tests/unit/test_drivers_matrix.sh

set -uo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "${WORK_DIR}"' EXIT

TESTS_RUN=0
TESTS_FAILED=0

ok() { printf '  PASS  %s\n' "$*"; }
nok() { printf '  FAIL  %s\n' "$*"; TESTS_FAILED=$((TESTS_FAILED + 1)); }

assert_has() {
    local label="$1" haystack="$2" needle="$3"
    TESTS_RUN=$((TESTS_RUN + 1))
    if grep -qF -- "${needle}" <<< "${haystack}"; then
        ok "${label}"
    else
        nok "${label}: missing '${needle}'"
        printf '%s\n' "${haystack}" \
            | grep -E '\[dry-run\]|^(family|init|fw_backend|ssh_unit|socket_setup|f2b_action|mac|mac_status|timesync|timezone_file|locale_files|audit_rules_file|pwquality_pkg|lockout_files|legacy_all)=' \
            | sed 's/^/        got: /'
    fi
}

assert_lacks() {
    local label="$1" haystack="$2" needle="$3"
    TESTS_RUN=$((TESTS_RUN + 1))
    if grep -qF -- "${needle}" <<< "${haystack}"; then
        nok "${label}: unexpectedly found '${needle}'"
    else
        ok "${label}"
    fi
}

assert_eq() {
    local label="$1" want="$2" got="$3"
    TESTS_RUN=$((TESTS_RUN + 1))
    if [[ "${want}" == "${got}" ]]; then
        ok "${label}"
    else
        nok "${label}: expected '${want}', got '${got}'"
    fi
}

assert_rc() {
    local label="$1" want="$2" got="$3"
    TESTS_RUN=$((TESTS_RUN + 1))
    if [[ "${want}" == "${got}" ]]; then
        ok "${label}"
    else
        nok "${label}: expected rc ${want}, got ${got}"
    fi
}

write_fixture() {
    local path="$1" id="$2" like="$3" version="$4"
    {
        printf 'NAME="%s"\n' "${id}"
        printf 'ID=%s\n' "${id}"
        if [[ -n "${like}" ]]; then
            printf 'ID_LIKE="%s"\n' "${like}"
        fi
        if [[ -n "${version}" ]]; then
            printf 'VERSION_ID="%s"\n' "${version}"
        fi
    } > "${path}"
}

new_stub_dir() {
    local dir="${WORK_DIR}/stub-$1"
    mkdir -p "${dir}"
    printf '%s' "${dir}"
}

# new_stub <dir> <name> <shell body>
new_stub() {
    local dir="$1" name="$2" body="$3"
    printf '#!/bin/sh\n%s\n' "${body}" > "${dir}/${name}"
    chmod +x "${dir}/${name}"
}

# A managed server: every unit the drivers look for is installed and running.
make_systemd_stubs() {
    new_stub "$1" systemctl 'case "$1" in
    is-active) exit 0 ;;
    list-unit-files) printf "%s\n" "sshd.service enabled" "ssh.service enabled" "ssh.socket enabled" "firewalld.service enabled" "ufw.service enabled" "dnf-automatic-install.timer enabled" "chronyd.service enabled" ;;
    esac
    exit 0'
}

# A minimal install: no unit is running and none is known.
make_systemd_stopped() {
    new_stub "$1" systemctl 'case "$1" in
    is-active) exit 1 ;;
    *) exit 0 ;;
    esac'
}

# sysvinit host: service(8) answers for everything.
make_sysv_stubs() {
    new_stub "$1" service 'exit 0'
    new_stub "$1" update-rc.d 'exit 0'
}

# ufw reports itself active and still allows the default SSH port, which is the
# state the stage has to move away from.
ufw_active_stub() {
    new_stub "$1" ufw 'if [ "$1" = "status" ]; then
    echo "Status: active"
    echo "22/tcp ALLOW IN Anywhere"
fi
exit 0'
}

ufw_inactive_stub() {
    new_stub "$1" ufw 'if [ "$1" = "status" ]; then
    echo "Status: inactive"
    echo "22/tcp ALLOW IN Anywhere"
fi
exit 0'
}

# Nothing is open yet, which is the state a fresh firewall starts from.
firewalld_cli_stub() {
    new_stub "$1" firewall-cmd 'case "$*" in
    *--query-port*|*--query-service*) exit 1 ;;
    esac
    exit 0'
    new_stub "$1" firewall-offline-cmd 'case "$*" in
    *--query-port*|*--query-service*) exit 1 ;;
    esac
    exit 0'
}

# A real apt host carries both: the driver runs apt-get and require_pkg_mgr looks
# for the front-end, so a fixture that claims the debian family needs both binaries
# on PATH even when the test host is a different family.
apt_stub() {
    new_stub "$1" apt-get 'exit 0'
    new_stub "$1" apt 'exit 0'
}

# Two locales are available; anything else has to be generated by the driver.
locale_stub() {
    new_stub "$1" locale 'if [ "$1" = "-a" ]; then printf "C\nC.UTF-8\nen_US.UTF-8\n"; fi
exit 0'
    new_stub "$1" locale-gen 'exit 0'
    new_stub "$1" update-locale 'exit 0'
    new_stub "$1" localectl 'exit 0'
    new_stub "$1" timedatectl 'exit 0'
}

# The driver refuses to install through a package manager that is not on PATH, so
# an RPM case needs the binary present. dnf is stubbed first because that is the
# one detect_os prefers when both exist.
rpm_pkg_stubs() {
    new_stub "$1" dnf 'exit 0'
    new_stub "$1" yum 'exit 0'
}

# The MAC, audit and PAM commands are host-specific, so every case is pointed at
# the same fixtures: two loadable AppArmor profiles plus the two entries that must
# be skipped, a permissive SELinux config and four stacks with a pam_unix line.
mac_fixture() {
    local dir="${WORK_DIR}/apparmor.d"
    mkdir -p "${dir}/local" "${WORK_DIR}/pam"
    printf '/bin/bash {\n}\n' > "${dir}/bash"
    printf '/bin/ping {\n}\n' > "${dir}/ping"
    printf '#include <tunables/global>\n' > "${dir}/tunables.global"
    printf 'SELINUX=permissive\nSELINUXTYPE=targeted\n' > "${WORK_DIR}/selinux"
    local stack
    for stack in common-auth common-account system-auth password-auth; do
        cat > "${WORK_DIR}/pam/${stack}" <<'EOF'
auth    [success=1 default=ignore]  pam_unix.so nullok
account required                    pam_unix.so
EOF
    done
}

# A driver checks a zone name against the zone database before it plans the change,
# and a slim image can ship without that database. The fixture is the database the
# pass reads, so every case sees the same answer for UTC whether or not the runner
# has tzdata installed.
zone_fixture() {
    mkdir -p "${WORK_DIR}/zoneinfo/Europe"
    printf 'UTC\n' > "${WORK_DIR}/zoneinfo/UTC"
    printf 'CET-1\n' > "${WORK_DIR}/zoneinfo/Europe/Berlin"
}

# Some plans depend on whether a host has a tool at all, and a stub directory can only
# add one: the runner's own binaries stay reachable underneath it, so an image that
# ships authselect would answer for the CentOS 7 case being described. A case says what
# its host does not have with this, and os_has_command reports it missing.
absent_commands() { export ABSENT_COMMANDS="$*"; }

# aa-status reports an enabled AppArmor and getenforce a permissive SELinux. Both
# audit loaders exist, so the transcript shows which one the driver prefers. A
# case that needs a different answer installs its own stub first: these are
# defaults, not overrides.
default_stub() {
    local dir="$1" name="$2" body="$3"
    if [[ ! -e "${dir}/${name}" ]]; then
        new_stub "${dir}" "${name}" "${body}"
    fi
}

mac_command_stubs() {
    default_stub "$1" getenforce 'echo Permissive'
    default_stub "$1" setenforce 'exit 0'
    default_stub "$1" aa-status 'if [ "$1" = "--enabled" ]; then exit 0; fi
echo "2 profiles are in enforce mode."
exit 0'
    default_stub "$1" aa-enforce 'exit 0'
    default_stub "$1" apparmor_status 'exit 0'
    default_stub "$1" augenrules 'exit 0'
    default_stub "$1" auditctl 'exit 0'
}

# run_driver <fixture> <stub dir> <init override> [locale to request]
# Prints what the loaded driver would do, with no changes to the host.
run_driver() {
    local fixture="$1" stub_dir="$2" init_override="$3" want_locale="${4:-en_US.UTF-8}"
    locale_stub "${stub_dir}"
    mac_command_stubs "${stub_dir}"
    (
        cd "${PROJECT_DIR}" || exit 1
        export OS_RELEASE_FILE="${fixture}"
        export PATH="${stub_dir}:${PATH}"
        export DRY_RUN=1
        export BACKUP_ROOT="${WORK_DIR}/backups"
        export STATE_DIR="${WORK_DIR}/state"
        export LOG_FILE="${WORK_DIR}/transcript.log"
        export SSH_PORT=2222
        export APPARMOR_PROFILE_DIR="${WORK_DIR}/apparmor.d"
        export SELINUX_CONFIG="${WORK_DIR}/selinux"
        export PAM_DIR="${WORK_DIR}/pam"
        export PAM_FAILLOCK_MODULE_PATH="${WORK_DIR}/pam/pam_faillock.so"
        export ZONEINFO_DIR="${WORK_DIR}/zoneinfo"
        # shellcheck disable=SC1091
        source lib/common.sh
        if ! detect_os > /dev/null 2>&1; then
            printf 'DETECT_FAILED\n'
            exit 1
        fi
        printf 'family=%s pkg=%s driver=%s id=%s version=%s\n' \
            "${OS_FAMILY}" "${PKG_MGR}" "${DRIVER}" "${OS_ID}" "${OS_VERSION}"
        if [[ -n "${init_override}" ]]; then
            INIT_SYSTEM="${init_override}"
        else
            detect_init > /dev/null 2>&1
        fi
        printf 'init=%s\n' "${INIT_SYSTEM}"

        backup_begin firewall > /dev/null 2>&1
        drv_fw_record_state
        printf 'fw_backend=%s\n' "$(drv_fw_backend)"
        drv_fw_install || printf 'fw_install_failed\n'
        drv_fw_apply_port 2222 ""
        drv_fw_deny_others
        drv_fw_enable
        printf 'ssh_unit=%s\n' "$(drv_ssh_unit || printf 'none')"
        if drv_ssh_socket_setup 2222; then
            printf 'socket_setup=done\n'
        else
            printf 'socket_setup=not_applicable\n'
        fi
        drv_f2b_prepare_repo
        printf 'f2b_action=%s\n' "$(drv_f2b_action)"
        drv_pkg_install fail2ban
        printf 'mac=%s\n' "$(drv_mac_name)"
        drv_mac_install
        printf 'sysctl_file=%s\n' "$(drv_sysctl_file)"
        printf 'audit_pkg=%s\n' "$(drv_audit_pkg)"
        printf 'timesync=%s/%s\n' "$(drv_timesync_pkg)" "$(drv_timesync_unit)"
        printf 'timezone_file=%s\n' "$(drv_timezone_file)"
        drv_timezone_apply UTC || printf 'timezone_failed\n'
        printf 'locale_files=%s\n' "$(drv_locale_files | tr '\n' ' ')"
        drv_locale_apply "${want_locale}" || printf 'locale_failed\n'
        drv_unattended_setup
        drv_crypto_policy DEFAULT || printf 'crypto_policy=unsupported\n'
        drv_updates_apply
        printf 'audit_rules_file=%s\n' "$(drv_audit_rules_file)"
        printf 'pwquality_pkg=%s\n' "$(drv_pwquality_pkg)"
        printf 'lockout_files=%s\n' "$(drv_lockout_files | tr '\n' ' ' | tr -s ' ')"
        drv_lockout_apply 4 300 600 || printf 'lockout_failed\n'
        printf 'legacy_all=%s\n' "$(drv_legacy_services all | tr '\n' ' ' | tr -s ' ')"
        drv_audit_apply || printf 'audit_apply_failed\n'
        printf 'mac_status=%s\n' "$(drv_mac_status)"
        drv_mac_enforce || printf 'mac_enforce_failed\n'
    ) 2>&1
}

